#!/usr/bin/env python3
"""SAT Math skills for the SAT Math Lib recommendation (ticket #40) → src/SmlSkills.gs.
   python3 tools/build_sml_skills.py "<project folder>/data/taxonomy/sat_skills.csv" "<project folder>/inbox_from_SML/SML_skills_checklist.csv"
Skill names (English) from sat_skills.csv; the difficulties SML allows per skill + "rare" from the SML checklist.
Only skill names and E/M/H letters (no question data), so it may be committed."""
import csv, json, os, sys
skills_csv, check_csv = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
names = {}
for r in csv.DictReader(open(skills_csv, encoding='utf-8')):
    if r['section'] == 'Math': names[r['skill']] = r['skill_name']
allowed, rare = {}, {}
for r in csv.DictReader(open(check_csv, encoding='utf-8')):
    s = r['skill']
    if s not in names: continue
    allowed[s] = [x.strip() for x in r['allowed_difficulties_in_SML'].split(',') if x.strip()]
    if 'rare' in (r.get('note') or '').lower(): rare[s] = True
out = {s: {'name': names[s], 'allowed': allowed.get(s, ['E', 'M', 'H']), 'rare': bool(rare.get(s))} for s in names}
assert len(out) == 19, len(out)
open(os.path.join(HERE, '..', 'src', 'SmlSkills.gs'), 'w', encoding='utf-8').write(
    '// GENERATED by tools/build_sml_skills.py from data/taxonomy/sat_skills.csv + inbox_from_SML/SML_skills_checklist.csv (#40).\n'
    '// SAT Math skill → English name, the difficulties SAT Math Lib allows (E/M/H), rare on the test (lowest priority).\n'
    'var SML_SKILLS_ = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('SmlSkills.gs: %d skills; limited: %s; rare: %s' % (len(out), {k: v['allowed'] for k, v in out.items() if v['allowed'] != ['E', 'M', 'H']}, sorted(rare)))
