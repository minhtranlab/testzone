#!/usr/bin/env python3
"""SAT score scale (ticket #2, SC FINAL 2026-11-09) → src/ScoreScale.gs = the default content of Sheet tab Score_Scale.
   python3 tools/build_score_scale.py "<project folder>/data/taxonomy"
Reads sat_score_scale.csv + sat_score_rules.csv. Public-source estimates only (no question data), so it may be committed.
At runtime the Score_Scale tab (Minh can edit it) wins; this file is the fallback and the content written when the tab is created."""
import csv, json, os, sys
src = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
scale = list(csv.reader(open(os.path.join(src, 'sat_score_scale.csv'), encoding='utf-8')))
rules = list(csv.reader(open(os.path.join(src, 'sat_score_rules.csv'), encoding='utf-8')))
out = ('// GENERATED by tools/build_score_scale.py from data/taxonomy/sat_score_scale.csv + sat_score_rules.csv (SC, FINAL 2026-11-09).\n'
       '// Default content of the Sheet tab Score_Scale; the tab (editable by Minh) is what the app reads.\n'
       'var SCORE_SCALE_DEFAULT_ = ' + json.dumps({'scale': scale, 'rules': rules}, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(os.path.join(HERE, '..', 'src', 'ScoreScale.gs'), 'w', encoding='utf-8').write(out)
print('ScoreScale.gs: %d scale rows, %d rules' % (len(scale) - 1, len(rules) - 1))
