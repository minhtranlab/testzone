#!/usr/bin/env python3
"""Writes tools/profiles/SAT-2026-*.json (Chat B, SAT round). One template, 5 forms. Directions are our own wording."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'profiles')

RW_DIR = ('<p>This section tests reading and writing skills. Each question comes with one or more short texts, which may include '
          'a table or a graph.</p><p>Read each text and question carefully, then choose the one best answer based on the text or texts.</p>'
          '<p>Every question in this section is multiple-choice with four answer choices (A–D). Each question has one best answer.</p>')
M_DIR = ('<p>This section tests math skills. Some questions are multiple-choice with four answer choices (A–D): choose the one best answer. '
         'For the other questions you type your own answer in a box (student-produced response); the rules for entering an answer are '
         'shown next to each of those questions.</p>'
         '<p>You may use the built-in calculator on any question (<b>Calculator</b>, top right). Common formulas are on the '
         '<b>Reference</b> sheet (top right).</p>'
         '<p><b>Unless a question says otherwise:</b></p><ul><li>All variables and expressions stand for real numbers.</li>'
         '<li>Figures are drawn to scale and lie in a plane.</li>'
         '<li>The domain of a function \\(f\\) is every real number \\(x\\) for which \\(f(x)\\) is a real number.</li></ul>')

FORMS = {
    'SAT-2026-08-I2': 'Practice Test · August 2026 (International)',
    'SAT-2026-09-USA': 'Practice Test · September 2026 (US)',
    'SAT-2026-09-I2': 'Practice Test · September 2026 (International)',
    'SAT-2026-10-A': 'Practice Test · October 2026',
    'SAT-2026-11-A': 'Practice Test · November 2026',
}


def profile(form_id, title, rw_sec=1920, m_sec=2100, n_rw=27, n_m=22, brk=600):
    rw = dict(section='RW', calculator=False, reference=False, annotate=True, layout='split', choices=4, can_return=False,
              time_limit_sec=rw_sec, n=n_rw, directions_html=RW_DIR)
    m = dict(section='Math', calculator=True, reference=True, annotate=False, layout='single', spr_layout='split', choices=4,
             can_return=False, time_limit_sec=m_sec, n=n_m, directions_html=M_DIR)
    parts = [
        dict(part='RW1', title='Section 1, Module 1: Reading and Writing', break_after_sec=0, **rw),
        dict(part='RW2', title='Section 1, Module 2: Reading and Writing', auto_start=True, break_after_sec=brk, pause_after=True, **rw),
        dict(part='M1', title='Section 2, Module 1: Math', break_after_sec=0, **m),
        dict(part='M2', title='Section 2, Module 2: Math', auto_start=True, break_after_sec=0, **m),
    ]
    return {
        'form_id': form_id, 'exam': 'SAT', 'title': title, 'track': 'SAT',
        'sections': [{'id': 'RW', 'title': 'Reading and Writing', 'parts': ['RW1', 'RW2']},
                     {'id': 'Math', 'title': 'Math', 'parts': ['M1', 'M2']}],
        'parts': parts, 'routing': [],
        'part_word': 'module', 'annotate_label': 'Highlights & Notes', 'practice_banner': True, 'reference_sheet': 'sat', 'question_font': 'serif',
        'pause_allowed_between_parts': False,
        '_note': 'Linear SAT form (SPEC §11): RW1 → RW2 (starts right after RW1) → 10-min break (only place to Save and Continue Later) '
                 '→ M1 (Directions + Begin) → M2 (starts right after M1). Desmos + Reference in Math only. Generated by tools/make_sat_profiles.py.'
    }


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for fid, title in FORMS.items():
        with open(os.path.join(OUT, fid + '.json'), 'w', encoding='utf-8') as fh:
            json.dump(profile(fid, title), fh, ensure_ascii=False, indent=1)
            fh.write('\n')
    print('wrote', len(FORMS), 'profiles to', os.path.abspath(OUT))
